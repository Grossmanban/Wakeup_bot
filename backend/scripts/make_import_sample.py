STATUS_TITLES = {
    "ok": "Загрузится",
    "error": "Ошибка",
    "duplicate": "Дубликат",
    "skipped": "Пропущена",
}
BOLD = Font(bold=True)
WRAP = Alignment(wrap_text=True, vertical="top")


def _widths(ws, widths: list[int]) -> None:
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def _tasks_sheet(wb: Workbook, rows) -> None:
    ws = wb.active
    ws.title = "Задания"
    ws.append(HEADER)
    for c in ws[1]:
        c.font = BOLD
    for values, status, _, _ in rows:
        ws.append(values)
        for c in ws[ws.max_row]:
            c.fill = FILLS[status]
            c.alignment = WRAP
    ws.freeze_panes = "B2"
    _widths(ws, [16, 22, 14, 40, 28, 9, 36, 24, 40, 10, 8, 14, 12])


def _setup_sheet(wb: Workbook) -> None:
    ws = wb.create_sheet("Настройка продуктов")
    ws.append(["Перед загрузкой создайте продукты («Управление» → «Продукты»)"])
    ws["A1"].font = BOLD
    ws.append([])
    ws.append(["Продукт", "Настройки"])
    for c in ws[3]:
        c.font = BOLD
    for p in PRODUCTS:
        ws.append([p["name"], p["setup"]])
        for c in ws[ws.max_row]:
            c.alignment = WRAP
    ws.append([])
    for note in (
        "Загрузка: «Управление» → «Импорт заданий» → выберите файл. Продукт выбирать не нужно — "
        "он указан в колонке «Продукт».",
        "Цвет строк на листе «Задания» — ожидаемый результат: зелёный — загрузится, красный — "
        "ошибка, жёлтый — дубликат, серый — пропуск.",
        "Колонки «Адрес точки» и «Менеджер» система не знает — они сохраняются как "
        "дополнительная информация задания.",
        "После подтверждения загрузите import-test-repeat.xlsx: уже загруженные ID будут "
        "отмечены как дубликаты, новые строки загрузятся.",
    ):
        ws.append([note])
    _widths(ws, [26, 110])


def _checks_sheet(wb: Workbook, rows) -> None:
    ws = wb.create_sheet("Что проверяем")
    ws.append(["Строка", "ID задания", "Ожидаемый результат", "Что проверяем", "Ожидаемые ошибки"])
    for c in ws[1]:
        c.font = BOLD
    for n, (values, status, what, errors) in enumerate(rows, start=2):
        ext = str(values[0]).strip()
        ext = ext if len(ext) < 40 else ext[:20] + "…"
        ws.append([n, ext, STATUS_TITLES[status], what, "; ".join(errors)])
        for c in ws[ws.max_row]:
            c.fill = FILLS[status]
            c.alignment = WRAP
    total = {s: sum(1 for r in rows if r[1] == s) for s in FILLS}
    ws.append([])
    ws.append(
        [
            "Итог",
            "",
            f"загрузится {total['ok']}, ошибок {total['error']}, "
            f"дубликатов {total['duplicate']}, пропущено {total['skipped']}",
        ]
    )
    ws[ws.max_row][0].font = BOLD
    _widths(ws, [8, 16, 20, 60, 60])


def build(rows, path: Path, with_setup: bool) -> None:
    wb = Workbook()
    _tasks_sheet(wb, rows)
    if with_setup:
        _setup_sheet(wb)
    _checks_sheet(wb, rows)
    wb.save(path)


def main(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    build(ROWS, out / "import-test.xlsx", with_setup=True)
    build(REPEAT_ROWS, out / "import-test-repeat.xlsx", with_setup=False)
    print(f"ok: {out / 'import-test.xlsx'}, {out / 'import-test-repeat.xlsx'}")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "."))
